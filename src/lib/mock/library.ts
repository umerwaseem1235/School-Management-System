export interface Book {
  id: string;
  accessionNo: string;
  title: string;
  author: string;
  isbn: string;
  category: string;
  publisher: string;
  edition: string;
  yearPublished: number;
  totalCopies: number;
  availableCopies: number;
  location: string;
  status: "Available" | "Low Stock" | "Out of Stock";
}

export interface IssuanceRecord {
  id: string;
  bookId: string;
  bookTitle: string;
  accessionNo: string;
  memberId: string;
  memberName: string;
  memberType: "Student" | "Staff" | "Faculty";
  className?: string;
  rollNo?: string;
  department?: string;
  issueDate: string;
  dueDate: string;
  returnDate?: string;
  status: "Issued" | "Returned" | "Overdue";
  fineAmount?: number;
  remarks?: string;
}

export interface LibraryMember {
  id: string;
  name: string;
  type: "Student" | "Staff" | "Faculty";
  className?: string;
  rollNo?: string;
  department?: string;
  email: string;
  phone: string;
  membershipDate: string;
  status: "Active" | "Suspended" | "Expired";
  booksIssued: number;
  maxLimit: number;
  totalFines: number;
}

export interface FineRecord {
  id: string;
  memberId: string;
  memberName: string;
  bookTitle: string;
  issueId: string;
  fineAmount: number;
  reason: string;
  dueDate: string;
  returnDate: string;
  daysOverdue: number;
  status: "Pending" | "Paid" | "Waived";
  paidDate?: string;
  waivedBy?: string;
}

